import { describe, expect, it } from "vitest";
import abiVectorJson from "./vectors/abi.json";
import abiFuzzJson from "./vectors/abi-fuzz.json";
import {
  decodeParameters,
  decodeSingle,
  decodeValues,
  encodeParameters,
  encodeValues,
  formatAbiType,
  isDynamic,
  parseAbiJson,
  parseAbiType,
  parseSignature,
  splitArgumentInput,
  staticByteSize,
} from "../abi";

const abiVectors = abiVectorJson as Array<{
  signature: string;
  args: string[];
  encoded: string;
  expected: string[];
}>;

describe("golden vectors produced by Foundry cast", () => {
  // Every expectation below was generated by an independent implementation.
  // A mismatch here means the codec disagrees with the reference, which is a
  // blocking defect in a tool that answers "what does this transaction do".
  for (const vector of abiVectors) {
    it(`round-trips ${vector.signature}`, () => {
      const signature = parseSignature(vector.signature);
      const encoded = `0x${encodeParameters(signature.inputs, vector.args)}`;
      expect(encoded).toBe(vector.encoded);

      const decoded = decodeParameters(signature.inputs, vector.encoded);
      expect(decoded.map((parameter) => parameter.value)).toEqual(vector.expected);
    });
  }
});

describe("frozen differential corpus", () => {
  // 240 randomly generated type/value combinations, each encoded by `cast
  // abi-encode` and frozen here so CI replays the same bytes without Foundry.
  // This is the regression net for nested arrays, tuples, and mixed shapes.
  const cases = abiFuzzJson as Array<{
    signature: string;
    args: string[];
    encoded: string;
    expected: string[];
  }>;

  it("covers a meaningful spread of shapes", () => {
    const shapes = new Set(cases.map((entry) => entry.signature));
    expect(cases.length).toBeGreaterThanOrEqual(200);
    expect([...shapes].some((signature) => signature.includes("[]"))).toBe(true);
    expect([...shapes].some((signature) => signature.includes("("))).toBe(true);
    expect([...shapes].some((signature) => signature.includes("[3]"))).toBe(true);
  });

  for (const [index, entry] of cases.entries()) {
    it(`matches cast on case ${index} ${entry.signature}`, () => {
      const signature = parseSignature(entry.signature);
      expect(`0x${encodeParameters(signature.inputs, entry.args)}`).toBe(entry.encoded);
      expect(decodeParameters(signature.inputs, entry.encoded).map((item) => item.value)).toEqual(entry.expected);
    });
  }
});

describe("parseAbiType", () => {
  it("accepts scalars and aliases", () => {
    expect(parseAbiType("uint256")).toEqual({ kind: "uint", bits: 256 });
    expect(parseAbiType("uint")).toEqual({ kind: "uint", bits: 256 });
    expect(parseAbiType("int8")).toEqual({ kind: "int", bits: 8 });
    expect(parseAbiType("bool")).toEqual({ kind: "bool" });
    expect(parseAbiType("address")).toEqual({ kind: "address" });
    expect(parseAbiType("address payable")).toEqual({ kind: "address" });
    expect(parseAbiType("bytes32")).toEqual({ kind: "bytesN", size: 32 });
    expect(parseAbiType("bytes")).toEqual({ kind: "bytes" });
    expect(parseAbiType("string")).toEqual({ kind: "string" });
  });

  it("accepts fixed, dynamic, and nested arrays", () => {
    expect(formatAbiType(parseAbiType("address[]"))).toBe("address[]");
    expect(formatAbiType(parseAbiType("uint256[2]"))).toBe("uint256[2]");
    expect(formatAbiType(parseAbiType("uint256[][3][]"))).toBe("uint256[][3][]");
  });

  it("accepts tuples, including nested and arrayed ones", () => {
    expect(formatAbiType(parseAbiType("(uint256,address)"))).toBe("(uint256,address)");
    expect(formatAbiType(parseAbiType("(uint256,address)[]"))).toBe("(uint256,address)[]");
    expect(formatAbiType(parseAbiType("((uint256,bytes),bool)[2]"))).toBe("((uint256,bytes),bool)[2]");
  });

  it("rejects nonsense instead of guessing", () => {
    expect(() => parseAbiType("uint7")).toThrow();
    expect(() => parseAbiType("uint264")).toThrow();
    expect(() => parseAbiType("bytes33")).toThrow();
    expect(() => parseAbiType("function")).toThrow();
    expect(() => parseAbiType("uint256[")).toThrow();
    expect(() => parseAbiType("uint256)")).toThrow();
    expect(() => parseAbiType("")).toThrow();
  });

  it("distinguishes dynamic from static types", () => {
    expect(isDynamic(parseAbiType("string"))).toBe(true);
    expect(isDynamic(parseAbiType("bytes"))).toBe(true);
    expect(isDynamic(parseAbiType("uint256[]"))).toBe(true);
    expect(isDynamic(parseAbiType("string[2]"))).toBe(true);
    expect(isDynamic(parseAbiType("uint256"))).toBe(false);
    expect(isDynamic(parseAbiType("uint256[2]"))).toBe(false);
    expect(isDynamic(parseAbiType("(uint256,address)"))).toBe(false);
    expect(isDynamic(parseAbiType("(uint256,string)"))).toBe(true);
    expect(staticByteSize(parseAbiType("uint256[2]"))).toBe(64);
    expect(staticByteSize(parseAbiType("(uint256,address)"))).toBe(64);
  });
});

describe("parseSignature", () => {
  it("normalises whitespace into one canonical form", () => {
    expect(parseSignature("reflectionFromToken(uint256, bool)").canonical).toBe("reflectionFromToken(uint256,bool)");
    expect(parseSignature("reflectionFromToken( uint256 ,bool )").canonical).toBe("reflectionFromToken(uint256,bool)");
    expect(parseSignature("transfer(address, uint)").canonical).toBe("transfer(address,uint256)");
  });

  it("captures returns in every suffix order seen in the wild", () => {
    for (const text of [
      "balanceOf(address) returns (uint256)",
      "balanceOf(address) view returns (uint256)",
      "balanceOf(address) external view returns (uint256)",
      "balanceOf(address) returns (uint256) view",
      "f() payable returns (uint256)",
      "function balanceOf(address owner) external view returns (uint256)",
    ]) {
      const signature = parseSignature(text);
      expect(signature.outputs, text).toHaveLength(1);
      expect(formatAbiType(signature.outputs[0].type)).toBe("uint256");
    }
  });

  it("keeps parameter names out of the canonical form", () => {
    const signature = parseSignature("transfer(address to, uint256 amount) external returns (bool)");
    expect(signature.canonical).toBe("transfer(address,uint256)");
    expect(signature.inputs.map((parameter) => parameter.name)).toEqual(["to", "amount"]);
  });

  it("records indexed on event parameters", () => {
    const signature = parseSignature("Transfer(address indexed from, address indexed to, uint256 value)", "event");
    expect(signature.canonical).toBe("Transfer(address,address,uint256)");
    expect(signature.inputs.map((parameter) => parameter.indexed)).toEqual([true, true, undefined]);
  });

  it("keeps bracketed commas inside the type", () => {
    expect(parseSignature("batch(address[],uint256)").inputs.map((p) => formatAbiType(p.type))).toEqual(["address[]", "uint256"]);
    expect(parseSignature("f((uint256,address),bool)").inputs).toHaveLength(2);
  });

  it("refuses trailing garbage instead of silently ignoring it", () => {
    expect(() => parseSignature("transfer(address,uint256) garbage")).toThrow();
    expect(() => parseSignature("f(uint256)UNRELATED")).toThrow();
    expect(() => parseSignature("approve(address,uint256)\ntransfer(address,uint256)")).toThrow();
  });

  it("refuses empty parameter slots instead of dropping them", () => {
    expect(() => parseSignature("f(uint256,,bool)")).toThrow();
    expect(() => parseSignature("f(uint256,)")).toThrow();
    expect(() => parseSignature("f(,)")).toThrow();
  });

  it("refuses unbalanced brackets", () => {
    expect(() => parseSignature("f(uint256")).toThrow();
    expect(() => parseSignature("f(uint256[)")).toThrow();
  });
});

describe("encoding", () => {
  it("range-checks numbers against the declared width", () => {
    expect(() => encodeValues([parseAbiType("uint8")], ["256"])).toThrow(/does not fit/);
    expect(() => encodeValues([parseAbiType("uint8")], ["255"])).not.toThrow();
    expect(() => encodeValues([parseAbiType("uint256")], ["-1"])).toThrow(/Negative/);
    expect(() => encodeValues([parseAbiType("int8")], ["-128"])).not.toThrow();
    expect(() => encodeValues([parseAbiType("int8")], ["-129"])).toThrow(/does not fit/);
  });

  it("rejects a mismatched argument count", () => {
    expect(() => encodeValues([parseAbiType("uint256"), parseAbiType("bool")], ["1"])).toThrow(/Expected 2/);
  });

  it("encodes signed hex literals instead of throwing a raw SyntaxError", () => {
    expect(encodeValues([parseAbiType("int256")], ["-1"])).toBe("f".repeat(64));
    expect(encodeValues([parseAbiType("int256")], ["-0x10"])).toMatch(/f0$/);
  });

  it("rejects odd-length bytesN rather than shifting the value", () => {
    expect(() => encodeValues([parseAbiType("bytes2")], ["0xabc"])).toThrow(/even number/);
    expect(encodeValues([parseAbiType("bytes2")], ["0x0abc"])).toBe("0abc" + "0".repeat(60));
  });

  it("requires JSON for arrays of comma-bearing types", () => {
    expect(() => encodeValues([parseAbiType("string[]")], ["a,bb"])).toThrow(/JSON array/);
    expect(encodeValues([parseAbiType("string[]")], ['["a,bb"]'])).toContain("612c6262");
  });

  it("checks fixed-size array lengths", () => {
    expect(() => encodeValues([parseAbiType("uint256[2]")], ["[1]"])).toThrow(/Expected 2 items/);
    expect(() => encodeValues([parseAbiType("uint256[2]")], ["[1,2,3]"])).toThrow(/Expected 2 items/);
  });
});

describe("decoding is fail-closed", () => {
  it("reads a uint256 return value", () => {
    expect(decodeValues([parseAbiType("uint256")], `0x${"0".repeat(62)}2a`)).toEqual(["42"]);
  });

  it("reads the reflection value observed at block 79788487", () => {
    const raw = "0x0000000000000024e4bba3a4875741cebfcc8b9890e7f3ccb5fcd119251c3e43";
    expect(decodeValues([parseAbiType("uint256")], raw)[0]).toBe("231584178474632390847141970017375815706539969331281128078915");
  });

  it("rejects dirty high bits instead of reporting an impossible value", () => {
    expect(() => decodeValues([parseAbiType("uint8")], `0x${"ff".repeat(32)}`)).toThrow(/dirty high bits/);
    expect(() => decodeValues([parseAbiType("bool")], `0x${"0".repeat(63)}2`)).toThrow(/not a valid bool/);
    expect(() => decodeValues([parseAbiType("address")], `0x${"ff".repeat(12)}${"11".repeat(20)}`)).toThrow(/not a valid address/);
  });

  it("rejects a declared length that exceeds the payload", () => {
    const word = (value: number) => value.toString(16).padStart(64, "0");
    expect(() => decodeValues([parseAbiType("string")], `0x${word(32)}${word(100)}41424344`)).toThrow(/exceeds the data size/);
    expect(() => decodeValues([parseAbiType("bytes")], `0x${word(32)}${word(100)}aabb`)).toThrow(/exceeds the data size/);
  });

  it("rejects an array length that would allocate absurdly", () => {
    const huge = "ff".repeat(32);
    expect(() => decodeValues([parseAbiType("uint256[]")], `0x${huge}${"0".repeat(64)}`)).toThrow();
  });

  it("bounds work when many offsets point at the same sub-array", () => {
    // A depth limit alone does not bound this: every element of every level can
    // point at the SAME next block, so a ~13 KB payload describes 100^4 values.
    // Before the node budget this hung the tab for over ten seconds.
    const word = (value: number) => value.toString(16).padStart(64, "0");
    const depth = 4;
    const width = 100;
    const levelStarts: number[] = [];
    let offset = 32;
    for (let level = 0; level < depth; level += 1) {
      levelStarts.push(offset);
      offset += 32 + width * 32;
    }
    const leafStart = offset;
    const blocks: string[] = [];
    for (let level = 0; level < depth; level += 1) {
      const nextStart = level + 1 < depth ? levelStarts[level + 1] : leafStart;
      let block = word(width);
      for (let index = 0; index < width; index += 1) block += word(nextStart - (levelStarts[level] + 32));
      blocks.push(block);
    }
    const payload = `0x${word(32)}${blocks.join("")}${word(0)}`;

    const started = Date.now();
    expect(() => decodeValues([parseAbiType(`uint256${"[]".repeat(depth)}`)], payload)).toThrow(/too many values/);
    expect(Date.now() - started).toBeLessThan(2000);
  });

  it("still decodes a legitimately large response", () => {
    // 2000 static words is a normal-sized payload; the budget must not bite.
    // A top-level dynamic value is laid out as: offset word, then the array
    // block (length word, then one word per item).
    const count = 2000;
    const body = Array.from({ length: count }, () => "0".repeat(63) + "1").join("");
    const payload = `0x${(32).toString(16).padStart(64, "0")}${count.toString(16).padStart(64, "0")}${body}`;
    const [value] = decodeValues([parseAbiType("uint256[]")], payload);
    expect(value.split(",").length).toBe(count);
  });

  it("explains empty return data instead of crashing", () => {
    expect(() => decodeValues([parseAbiType("uint256")], "0x")).toThrow(/empty/);
    expect(decodeValues([], "0x")).toEqual([]);
  });

  it("fails loudly on truncated data", () => {
    expect(() => decodeValues([parseAbiType("uint256")], "0x1234")).toThrow(/shorter/);
    expect(() => decodeValues([parseAbiType("bytes32")], `0x${"cd".repeat(8)}`)).toThrow(/shorter/);
  });

  it("rejects non-hex and odd-length payloads", () => {
    expect(() => decodeValues([parseAbiType("uint256")], "0xzz")).toThrow(/non-hex/);
    expect(() => decodeValues([parseAbiType("uint256")], "0xabc")).toThrow(/odd number/);
  });

  it("decodes a single indexed topic word", () => {
    expect(decodeSingle(parseAbiType("address"), `0x${"0".repeat(24)}${"ab".repeat(20)}`)).toBe(`0x${"ab".repeat(20)}`);
    expect(decodeSingle(parseAbiType("uint256"), `0x${"0".repeat(62)}07`)).toBe("7");
  });
});

describe("parseAbiJson", () => {
  const abi = JSON.stringify([
    { type: "function", name: "transfer", inputs: [{ name: "to", type: "address" }, { name: "amount", type: "uint256" }], outputs: [{ name: "", type: "bool" }], stateMutability: "nonpayable" },
    { type: "constructor", inputs: [{ name: "supply", type: "uint256" }], stateMutability: "nonpayable" },
    { type: "event", name: "Transfer", inputs: [{ name: "from", type: "address", indexed: true }, { name: "to", type: "address", indexed: true }, { name: "value", type: "uint256", indexed: false }], anonymous: false },
    { type: "function", name: "set", inputs: [{ name: "config", type: "tuple", components: [{ name: "a", type: "uint256" }, { name: "b", type: "string" }] }], outputs: [], stateMutability: "nonpayable" },
    { type: "fallback", stateMutability: "payable" },
  ]);

  it("extracts functions, constructors, and events", () => {
    const items = parseAbiJson(abi);
    expect(items.map((item) => item.kind)).toEqual(["function", "constructor", "event", "function"]);
    const transfer = items[0];
    expect(transfer.kind === "function" && transfer.signature.canonical).toBe("transfer(address,uint256)");
    expect(transfer.kind === "function" && transfer.outputs).toHaveLength(1);
  });

  it("carries tuple components through", () => {
    const items = parseAbiJson(abi);
    const set = items[3];
    expect(set.kind === "function" && formatAbiType(set.inputs[0].type)).toBe("(uint256,string)");
  });

  it("marks indexed event parameters", () => {
    const items = parseAbiJson(abi);
    const event = items[2];
    expect(event.kind === "event" && event.inputs.map((input) => input.indexed)).toEqual([true, true, undefined]);
  });

  it("rejects malformed ABI", () => {
    expect(() => parseAbiJson("{}")).toThrow(/array/);
    expect(() => parseAbiJson("not json")).toThrow(/valid JSON/);
    expect(() => parseAbiJson('[{"type":"function"}]')).toThrow(/missing its name/);
  });
});

describe("splitArgumentInput", () => {
  it("keeps a string argument intact", () => {
    const types = [parseAbiType("string")];
    expect(splitArgumentInput("hello, world", types)).toEqual(["hello, world"]);
    expect(splitArgumentInput("  padded  ", types)).toEqual(["  padded  "]);
  });

  it("uses one line per argument when there are commas to protect", () => {
    const types = [parseAbiType("string"), parseAbiType("string"), parseAbiType("string")];
    expect(splitArgumentInput("a\nb\nc", types)).toEqual(["a", "b", "c"]);
  });

  it("still allows a comma list for purely scalar parameters", () => {
    const types = [parseAbiType("uint256"), parseAbiType("bool")];
    expect(splitArgumentInput("1, false", types)).toEqual(["1", "false"]);
  });

  it("reports a line count mismatch", () => {
    const types = [parseAbiType("string"), parseAbiType("string")];
    expect(() => splitArgumentInput("only-one", types)).toThrow();
  });
});
